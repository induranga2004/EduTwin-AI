"""Graph providers: payload passthrough, deterministic mock graph, C1 API stub."""

import pytest

from edusync_c2.difficulty.graph import GraphView
from edusync_c2.difficulty.providers import (
    C1ApiGraphProvider,
    MockC1GraphProvider,
    PayloadGraphProvider,
    slugify,
)
from edusync_c2.difficulty.schemas import C1GraphResponse, MaterialsDoc


def test_slugify() -> None:
    assert slugify("  Loss   Function ") == "loss function"


def test_payload_provider(deck: MaterialsDoc, graph_v1: C1GraphResponse) -> None:
    ctx = PayloadGraphProvider(graph_v1).build(deck)
    assert ctx.response is graph_v1
    assert (ctx.source.name, ctx.source.kind) == ("c1_graph", "real")
    assert "not verified by C2" in ctx.source.detail
    assert PayloadGraphProvider.name == "payload"


def test_mock_provider_graph(deck: MaterialsDoc) -> None:
    ctx = MockC1GraphProvider().build(deck)
    assert ctx.source.kind == "mock"
    resp = C1GraphResponse.model_validate(ctx.response.model_dump())
    assert resp.lecture_id is None
    assert resp.filename == "lecture.pptx"
    assert resp.message == "Mock graph generated by C2 (Phase 1 placeholder, not from C1)."
    assert resp.graph.note
    assert "placeholder" in resp.graph.note
    ids = [n.id for n in resp.graph.nodes]
    # "Questions?" is skipped
    assert ids == ["gradient descent", "learning rate", "loss function", "backpropagation"]
    assert resp.concept_count == 4 == resp.graph.node_count
    assert resp.graph.edge_count == len(resp.graph.edges)
    assert all(n.description is None and n.frequency >= 1 for n in resp.graph.nodes)
    assert resp.graph.nodes[0].frequency == 2  # slides 1 and 2


def test_mock_prerequisite_chain_follows_slide_order(deck: MaterialsDoc) -> None:
    resp = MockC1GraphProvider().build(deck).response
    pre = [e for e in resp.graph.edges if e.relation_type == "prerequisite"]
    assert [(e.source, e.target) for e in pre] == [
        ("gradient descent", "learning rate"),
        ("learning rate", "loss function"),
        ("loss function", "backpropagation"),
    ]
    assert all(
        e.confidence == 0.5
        and e.source_type == "inferred"
        and e.direction == "source_is_prerequisite_of_target"
        for e in pre
    )
    view = GraphView(resp)
    assert view.warnings == []
    m = view.metrics("backpropagation")
    assert m is not None
    assert m.chain_depth == 3


def test_mock_co_mention_evidence(deck: MaterialsDoc) -> None:
    resp = MockC1GraphProvider().build(deck).response
    co = [e for e in resp.graph.edges if e.relation_type == "co_mentioned"]
    pairs = {(e.source, e.target): e for e in co}
    e = pairs[("gradient descent", "learning rate")]
    assert [ev.page for ev in e.evidence] == [2]
    assert e.evidence[0].sentence == (
        "The learning rate controls the step size of gradient descent."
    )
    assert e.evidence_count == 1
    assert e.direction is None
    assert e.confidence is None


def test_mock_is_deterministic(deck: MaterialsDoc) -> None:
    a = MockC1GraphProvider().build(deck)
    b = MockC1GraphProvider().build(deck)
    assert a.model_dump() == b.model_dump()


def test_mock_dedupes_titles_and_truncates_evidence(make_slide) -> None:
    long = "alpha beta " + "x" * 400
    doc = MaterialsDoc(
        filename="d.pdf",
        file_type="pdf",
        slide_count=4,
        structure_available=False,
        slides=[
            make_slide(1, "Alpha", title="Alpha"),
            make_slide(2, "alpha\nbeta", title=" ALPHA "),
            make_slide(3, long, title="Beta"),
            make_slide(4, "...", title="..."),
        ],
    )
    resp = MockC1GraphProvider().build(doc).response
    assert [n.id for n in resp.graph.nodes] == ["alpha", "beta"]
    co = [e for e in resp.graph.edges if e.relation_type == "co_mentioned"]
    assert len(co) == 1
    first, last = co[0].evidence
    assert (first.page, first.sentence) == (2, "alpha beta")  # fallback: slide text start
    assert (last.page, len(last.sentence)) == (3, 200)


def test_mock_empty_deck(make_slide) -> None:
    doc = MaterialsDoc(
        filename="e.pptx",
        file_type="pptx",
        slide_count=1,
        structure_available=True,
        slides=[make_slide(1, "text", title=None)],
    )
    resp = MockC1GraphProvider().build(doc).response
    assert resp.graph.nodes == []
    assert resp.graph.edges == []


